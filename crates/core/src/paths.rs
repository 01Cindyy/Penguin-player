use std::io;
use std::path::{Path, PathBuf};

use crate::app_info::{APP_DIR_NAME, APP_ORGANIZATION, APP_QUALIFIER};
use crate::model::CoverId;

/// Setting this environment variable to a directory keeps all config, data and cache
/// inside it ("portable mode"). Also handy for testing without touching real user data.
pub const HOME_OVERRIDE_ENV: &str = "PENGUIN_PLAYER_HOME";

/// Where the app keeps its files. Uses the platform conventions
/// (XDG on Linux, `~/Library` on macOS, `%APPDATA%` on Windows).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AppPaths {
    pub config_dir: PathBuf,
    pub data_dir: PathBuf,
    pub cache_dir: PathBuf,
}

impl AppPaths {
    pub fn resolve() -> io::Result<Self> {
        if let Some(root) = std::env::var_os(HOME_OVERRIDE_ENV).filter(|value| !value.is_empty()) {
            return Ok(Self::from_root(Path::new(&root)));
        }
        let dirs = directories::ProjectDirs::from(APP_QUALIFIER, APP_ORGANIZATION, APP_DIR_NAME)
            .ok_or_else(|| {
                io::Error::new(
                    io::ErrorKind::NotFound,
                    "could not determine the home directory",
                )
            })?;
        Ok(Self {
            config_dir: dirs.config_dir().to_path_buf(),
            data_dir: dirs.data_dir().to_path_buf(),
            cache_dir: dirs.cache_dir().to_path_buf(),
        })
    }

    pub fn from_root(root: &Path) -> Self {
        Self {
            config_dir: root.join("config"),
            data_dir: root.join("data"),
            cache_dir: root.join("cache"),
        }
    }

    /// Creates every directory the app writes to.
    pub fn ensure_dirs(&self) -> io::Result<()> {
        for dir in [
            self.config_dir.clone(),
            self.data_dir.clone(),
            self.cache_dir.clone(),
            self.themes_dir(),
            self.plugins_dir(),
            self.plugin_data_dir(),
            self.covers_dir(),
            self.thumbnails_dir(),
            self.lyrics_dir(),
        ] {
            std::fs::create_dir_all(dir)?;
        }
        Ok(())
    }

    pub fn settings_file(&self) -> PathBuf {
        self.config_dir.join("settings.json")
    }

    /// User themes, one folder per theme containing `theme.json`.
    pub fn themes_dir(&self) -> PathBuf {
        self.config_dir.join("themes")
    }

    /// User plugins, one folder per plugin containing `plugin.json`.
    pub fn plugins_dir(&self) -> PathBuf {
        self.config_dir.join("plugins")
    }

    /// Persistent storage that plugins write through the plugin API.
    pub fn plugin_data_dir(&self) -> PathBuf {
        self.data_dir.join("plugin-data")
    }

    pub fn library_db(&self) -> PathBuf {
        self.data_dir.join("library.db")
    }

    /// Full-size cover images extracted by the library scanner.
    pub fn covers_dir(&self) -> PathBuf {
        self.cache_dir.join("covers")
    }

    /// Downscaled covers generated by the UI.
    pub fn thumbnails_dir(&self) -> PathBuf {
        self.cache_dir.join("thumbnails")
    }

    /// Lyrics that plugins found online, kept so they are only looked up once.
    pub fn lyrics_dir(&self) -> PathBuf {
        self.cache_dir.join("lyrics")
    }

    pub fn cover_path(&self, cover: &CoverId) -> PathBuf {
        self.covers_dir().join(&cover.0)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn layout_under_root() {
        let paths = AppPaths::from_root(Path::new("/tmp/mp"));
        assert_eq!(
            paths.settings_file(),
            Path::new("/tmp/mp/config/settings.json")
        );
        assert_eq!(paths.library_db(), Path::new("/tmp/mp/data/library.db"));
        assert_eq!(
            paths.cover_path(&CoverId("ab.jpg".into())),
            Path::new("/tmp/mp/cache/covers/ab.jpg")
        );
    }
}
